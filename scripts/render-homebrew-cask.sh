#!/bin/sh
set -eu

if [ "$#" -ne 2 ]; then
	echo "usage: $0 VERSION CHECKSUMS_FILE" >&2
	exit 2
fi

version="$1"
checksums="$2"

case "$version" in
	v* | "" | *"'"* | *'"'* | *'
'*)
		echo "invalid version (expected semver without leading v): $version" >&2
		exit 2
		;;
esac

if [ ! -f "$checksums" ]; then
	echo "checksums file not found: $checksums" >&2
	exit 2
fi

lookup_sha() {
	asset="$1"
	sha=$(awk -v target="$asset" '
		{
			file = $2
			sub(/^.*\//, "", file)
			if (file == target) {
				print $1
				exit
			}
		}
	' "$checksums")
	if [ -z "$sha" ]; then
		echo "missing checksum for $asset in $checksums" >&2
		exit 1
	fi
	case "$sha" in
		*[!0-9a-fA-F]*)
			echo "invalid sha256 for $asset: $sha" >&2
			exit 1
			;;
	esac
	if [ "${#sha}" -ne 64 ]; then
		echo "invalid sha256 length for $asset: $sha" >&2
		exit 1
	fi
	printf '%s\n' "$sha"
}

darwin_arm64=$(lookup_sha "bmux_darwin_arm64.tar.gz")
darwin_amd64=$(lookup_sha "bmux_darwin_amd64.tar.gz")
linux_arm64=$(lookup_sha "bmux_linux_arm64.tar.gz")
linux_amd64=$(lookup_sha "bmux_linux_amd64.tar.gz")

cat <<EOF
# This file was generated by GoReleaser. DO NOT EDIT.
cask "bmux" do
  version "$version"

  on_macos do
    on_arm do
      sha256 "$darwin_arm64"
      url "https://github.com/bmux-dev/bmux/releases/download/v#{version}/bmux_darwin_arm64.tar.gz"
    end
    on_intel do
      sha256 "$darwin_amd64"
      url "https://github.com/bmux-dev/bmux/releases/download/v#{version}/bmux_darwin_amd64.tar.gz"
    end
  end
  on_linux do
    on_arm do
      sha256 "$linux_arm64"
      url "https://github.com/bmux-dev/bmux/releases/download/v#{version}/bmux_linux_arm64.tar.gz"
    end
    on_intel do
      sha256 "$linux_amd64"
      url "https://github.com/bmux-dev/bmux/releases/download/v#{version}/bmux_linux_amd64.tar.gz"
    end
  end

  name "bmux"
  desc "The batteries-included terminal multiplexer built for coding agents"
  homepage "https://bmux-dev.github.io/bmux/"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "bmux"

  postflight_steps do
    on_macos do
      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{staged_path}}/bmux"]
    end
  end

  zap :not_required
end
EOF
