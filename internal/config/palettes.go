// Palette is the chrome colors of one theme, as 0xRRGGBB values. Light themes
// pick the light shades of the accent shortcuts amber, green and cyan.
type Palette struct {
	Light                                                                bool
	Foreground, Background, Muted, Bar, Accent, Selection, SelectionText int32
	Working, Blocked, Waiting, Idle, Unknown                             int32
}

